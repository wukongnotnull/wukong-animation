import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { initializeProduction } from '../../plugin/engine/core/state.mjs';
import { buildManifest, writeManifest, verifyManifest } from '../../plugin/engine/core/delivery-manifest.mjs';

function film(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'wka-manifest-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  initializeProduction(dir);
  const put = (name, text) => {
    const file = path.join(dir, name);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
  };
  put('film.json', JSON.stringify({
    title: '清单', style: 'keynote', size: [1080, 1920], fps: 30, seed: 1,
    scripts: ['scripts/shared.mjs'], shots: [{ id: 's01', file: 'shots/s01.tsx', duration: 2 }],
    audio: { build: 'audio/build.mjs' }, export: { formats: ['mp4'], name: 'out' },
  }));
  put('brief.md', '简报');
  put('story.md', '剧本');
  put('storyboard.md', '分镜');
  put('shots/s01.tsx', 'shot');
  put('scripts/shared.mjs', 'shared');
  put('audio/build.mjs', 'audio');
  put('review/小样.mp4', 'sample-v1');
  put('review/QC报告-proxy.json', '{"ok":true}');
  put('out.mp4', 'final-v1');
  put('review/QC报告.json', '{"final":true}');
  return { dir, put };
}

test('a text step includes its source files and excludes generated media', t => {
  const { dir } = film(t);
  const manifest = buildManifest(dir, 3);
  assert.deepEqual(manifest.tracked.sort(), ['brief.md', 'film.json', 'story.md'].sort());
  assert.equal(manifest.generated.length, 0);
});

test('a generated step records media checksums without making media committable', t => {
  const { dir } = film(t);
  const manifest = buildManifest(dir, 5);
  assert.deepEqual(manifest.tracked.sort(), ['audio/build.mjs', 'brief.md', 'film.json', 'scripts/shared.mjs', 'shots/s01.tsx', 'story.md', 'storyboard.md'].sort());
  const sample = manifest.generated.find(item => item.path === 'review/小样.mp4');
  assert.equal(sample.bytes, Buffer.byteLength('sample-v1'));
  assert.match(sample.sha256, /^[a-f0-9]{64}$/);
  assert.equal(manifest.tracked.includes('review/小样.mp4'), false);
});

test('user recordings and alignment stay with the sources that rebuild the film', t => {
  const { dir, put } = film(t);
  put('audio/voice.wav', 'wav');
  put('.wka/voice-alignment.json', '{}\n');
  const saved = JSON.parse(fs.readFileSync(path.join(dir, 'film.json'), 'utf8'));
  saved.audio.voices = [{ cue: 'v', file: 'audio/voice.wav', at: 0, text: '你好' }];
  saved.variants = { '16:9': {} };
  fs.writeFileSync(path.join(dir, 'film.json'), JSON.stringify(saved));
  put('shots/s01.16x9.tsx', 'landscape');
  const manifest = buildManifest(dir, 6);
  assert.equal(manifest.tracked.includes('audio/voice.wav'), true);
  assert.equal(manifest.tracked.includes('.wka/voice-alignment.json'), true);
  assert.equal(manifest.tracked.includes('shots/s01.16x9.tsx'), true);
  assert.equal(manifest.tracked.includes('out.mp4'), false);
});

test('changing one generated byte makes the saved manifest fail', t => {
  const { dir, put } = film(t);
  writeManifest(dir, buildManifest(dir, 6));
  assert.equal(verifyManifest(dir).ok, true);
  put('out.mp4', 'final-v2');
  const result = verifyManifest(dir);
  assert.equal(result.ok, false);
  assert.match(result.reason, /out\.mp4/);
});
